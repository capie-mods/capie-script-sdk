# ---- Localisation -----------------------------------------------------------------------------


def loc_line(key: str, value: str) -> str:
    """Return one localisation line.

    Args:
        key: Key.
        value: Text (no double quotes inside).

    Returns:
        `` KEY:0 "value"`` with a newline.

    Raises:
        ValueError: The value holds a double quote.
    """
    if '"' in value:
        msg = f"localisation value of {key} holds a double quote"
        raise ValueError(msg)
    return f' {key}:0 "{value}"\n'


def gen_localisation(language: str) -> str:
    """Return ``capie_sdk_v1_l_<language>.yml`` (without the BOM).

    Args:
        language: HOI4 language folder.

    Returns:
        File text.
    """
    pick = 1 if language == POLISH else 0
    lines = [
        f"l_{language}:\n",
        " # GENERATED by sdk/capie-script-sdk/tools/gen_sdk.py - CAPIE script SDK v1\n",
    ]
    lines += [loc_line(key, texts[pick]) for key, texts in UI_TEXT.items()]
    lines += [loc_line(f"CAPIE_V1_ERR_{code}", texts[pick]) for code, texts in ERRORS.items()]
    lines += [loc_line(f"CAPIE_V1_TXT{slot}", slot_text(slot)) for slot in range(1, SLOTS + 1)]
    lines.append(loc_line("CAPIE_CH_0", ""))
    lines += [loc_line(f"CAPIE_CH_{code}", CHARS[code]) for code in range(1, LAST_CODE + 1)]
    return "".join(lines)


# ---- Output -----------------------------------------------------------------------------------


def outputs() -> dict[Path, bytes]:
    """Return every generated file and its bytes.

    Returns:
        Path under :data:`OUT` to file bytes (UTF-8; localisation with a BOM).
    """
    files: dict[str, tuple[str, bool]] = {
        "common/scripted_triggers/capie_sdk_v1_triggers.txt": (gen_triggers(), False),
        "common/scripted_effects/capie_sdk_v1_effects.txt": (gen_effects(), False),
        "common/scripted_localisation/capie_sdk_v1_text.txt": (gen_scripted_loc(), False),
        "common/game_rules/capie_sdk_v1_rules.txt": (template("capie_sdk_v1_rules.txt"), False),
        "common/scripted_guis/capie_sdk_v1_hello.txt": (template("capie_sdk_v1_hello.txt"), False),
        "interface/capie_sdk_v1_hello.gui": (template("capie_sdk_v1_hello.gui"), False),
    }
    for language in LANGUAGES:
        files[f"localisation/{language}/capie_sdk_v1_l_{language}.yml"] = (
            gen_localisation(language),
            True,
        )
    return {
        OUT / rel: (b"\xef\xbb\xbf" if bom else b"") + text.encode("utf-8")
        for rel, (text, bom) in files.items()
    }


def main() -> int:
    """Write the SDK, or compare it with the files on disk.

    Returns:
        Process exit code.
    """
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="compare instead of writing")
    args = parser.parse_args()
    stale = []
    for path, data in outputs().items():
        if args.check:
            if not path.exists() or path.read_bytes() != data:
                stale.append(path)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
    for path in stale:
        print(f"stale: {path.relative_to(SDK_ROOT).as_posix()}")
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
