def gen_scripted_loc() -> str:
    """Return ``capie_sdk_v1_text.txt``: one ``defined_text`` per slot position and the error line.

    Returns:
        File text.
    """
    out = [HEADER]
    for slot in range(1, SLOTS + 1):
        for i in range(MAX_FIELD_LENGTH):
            out.append(f"defined_text = {{\n\tname = CAPIE_V1_T{slot}_{i}\n")
            out.append(
                f"\ttext = {{ trigger = {{ NOT = {{ {check(f'capie_v1_txt{slot}_len > {i}')} }} }} "
                "localization_key = CAPIE_CH_0 }\n"
            )
            out.extend(
                f"\ttext = {{ trigger = {{ {check(f'capie_v1_txt{slot}^{i} = {code}')} }} "
                f"localization_key = CAPIE_CH_{code} }}\n"
                for code in range(1, LAST_CODE + 1)
            )
            out.append("\ttext = { localization_key = CAPIE_CH_0 }\n}\n")
    out.append("defined_text = {\n\tname = CAPIE_V1_LAST_ERROR\n")
    out.append(text_branch(check("capie_v1_last_err = 0"), "CAPIE_V1_ERR_0"))
    out.extend(
        text_branch(check(f"capie_v1_last_err = {code}"), f"CAPIE_V1_ERR_{code}") for code in ERRORS
    )
    out.append("\ttext = { localization_key = CAPIE_V1_ERR_UNKNOWN }\n}\n")
    return "".join(out)


