#!/usr/bin/env python3
"""Generate the CAPIE script SDK v1 (API level 2) into ``sdk/capie-script-sdk/mod/``.

The SDK is plain HOI4 script: scripted triggers, scripted effects, scripted
localisation, one game rule, the CAPIE check window and localisation for every game
language. Mods list the SDK's Workshop item as a dependency and call its
``capie_v1_*`` effects from their own Apply buttons; the contract they rely on is
``plugin/capie/CONTRACT.md``.

What the SDK gives a mod:

* ``capie_v1_begin``: reads the command header CAPIE added (``capie_cap``, ``capie_ver``,
  ``capie_epoch``), notes CAPIE presence for the multiplayer handshake and sets
  ``capie_err`` (10 CAPIE missing, 11 too old, 12 stale opening, 13 registry full,
  14 layout invalid, 16 multiplayer lock).
* ``capie_v1_field_load``: copies field ``capie_field`` into the work buffer
  ``capie_c0 .. capie_c31`` / ``capie_len`` and checks it (21..26 transport errors,
  35 malformed payload).
* Text tools in plain script (C5): trim, validation (31..34), compare with a slot,
  store into and load from four text slots per country, and scripted localisation that
  draws a slot (``CAPIE_V1_TXT<n>``).
* Setters for the vanilla name effects through ``meta_effect`` (country name through the
  country-name layer of API level 4, state, character, party names).
* Permission triggers and the ``capie_v1_edit_rights`` game rule.
* The CAPIE check window of the multiplayer handshake (``capie_v1_ed__capie__hello``).

Everything here works without CAPIE: the effects then take their error branch.

Usage::

    uv run python sdk/capie-script-sdk/tools/gen_sdk.py [--check]

``--check`` compares the generated text with the files on disk and exits 1 on a
difference instead of writing.
"""

